def test_device_crud_roundtrip(auth_client):
    created = auth_client.post("/api/devices", json={
        "type": "pwm_led_strip", "name": "Desk", "room": "Office",
        "uid": "desk-strip", "config": {"pin": 6},
    })
    assert created.status_code == 201, created.text
    device = created.json()
    assert device["uid"] == "desk-strip"
    assert device["config"]["pin"] == 6
    assert device["desired"]["brightness"] == 100
    # Reject duplicates and unknown types with a 4xx and a readable message.
    duplicate = auth_client.post("/api/devices", json={"type": "relay", "uid": "desk-strip"})
    assert duplicate.status_code == 400
    assert "already exists" in duplicate.json()["error"]
    assert auth_client.post("/api/devices", json={"type": "nope"}).status_code == 400

    listing = auth_client.get("/api/devices").json()["devices"]
    assert [d["uid"] for d in listing] == ["desk-strip"]

    renamed = auth_client.patch("/api/devices/desk-strip", json={"name": "Desk lamp", "room": "Den"})
    assert renamed.status_code == 200
    assert renamed.json()["name"] == "Desk lamp"

    bad = auth_client.patch("/api/devices/desk-strip", json={"config": {"pin": 999}})
    assert bad.status_code == 400

    deleted = auth_client.delete("/api/devices/desk-strip")
    assert deleted.status_code == 200
    assert auth_client.get("/api/devices").json()["devices"] == []
    assert auth_client.delete("/api/devices/desk-strip").status_code == 404


