def test_patch_does_not_unassign_a_device_by_accident(auth_client):
    """A PATCH without node_id must leave the binding alone."""
    auth_client.post("/api/devices", json={"type": "relay", "uid": "keep-node", "name": "K"})
    # Give it a node by letting a websocket announce it is overkill here; use
    # the hub directly through a second device created with a node_id.
    token = auth_client.post("/api/nodes/esp-keep/token", json={}).json()["token"]
    with auth_client.websocket_connect("/ws/node?node=esp-keep&token=" + token) as socket:
        socket.send_text(json.dumps({
            "t": "hello", "node": "esp-keep", "devices": [
                {"uid": "keep-node", "type": "relay", "state": {"power": False}},
            ],
        }))
        _drain_until(socket, "hello")

        renamed = auth_client.patch("/api/devices/keep-node", json={"name": "Renamed"})
        assert renamed.status_code == 200
        assert renamed.json()["node_id"] == "esp-keep"

        # Explicit null does unassign.
        cleared = auth_client.patch("/api/devices/keep-node", json={"node_id": None})
        assert cleared.status_code == 200
        assert cleared.json()["node_id"] is None


def _drain_until(socket, kind: str) -> dict:
    message = json.loads(socket.receive_text())
    while message.get("t") != kind:
        message = json.loads(socket.receive_text())
    return message


