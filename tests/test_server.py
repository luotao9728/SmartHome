def test_node_websocket_enrollment_flow(client, config):
    # Open the window as an admin, then connect like a fresh board would.
    client.post("/api/login", json={"password": PASSWORD})
    client.post("/api/enroll", json={"seconds": 60})
    with client.websocket_connect("/ws/node?node=esp-new") as socket:
        enrolled = json.loads(socket.receive_text())
        assert enrolled["t"] == "enrolled"
        token = enrolled["token"]
        assert token.startswith("shd_")
        socket.send_text(json.dumps({
            "t": "hello", "node": "esp-new", "board": "esp32-c6", "fw": "1.0.0",
            "devices": [{"uid": "relay-a", "type": "relay", "name": "Relay A"}],
        }))
        # hello reply, then possibly a reconcile command
        first = json.loads(socket.receive_text())
        assert first["t"] in ("hello", "cmd")
        if first["t"] == "cmd":
            socket.send_text(json.dumps({"t": "ack", "id": first["id"], "ok": True}))
            first = json.loads(socket.receive_text())
        assert first["t"] == "hello"

    store = Store(config.db_path)
    try:
        assert store.node_token_hash("esp-new") == security.hash_device_token(token)
    finally:
        store.close()


def test_node_hello_over_websocket_creates_devices(auth_client, config):
    token = auth_client.post("/api/nodes/esp-7/token", json={}).json()["token"]
    with auth_client.websocket_connect("/ws/node?node=esp-7&token=" + token) as socket:
        socket.send_text(json.dumps({
            "t": "hello", "node": "esp-7", "board": "esp32-c6", "fw": "1.0.0", "ip": "10.0.0.7",
            "devices": [{"uid": "strip-7", "type": "pwm_led_strip", "name": "Strip 7",
                         "state": {"power": True, "brightness": 55}}],
        }))
        reply = json.loads(socket.receive_text())
        while reply["t"] != "hello":
            reply = json.loads(socket.receive_text())
        assert reply["v"] == 1

        # The device shows up in the API with reported state from the board.
        devices = auth_client.get("/api/devices").json()["devices"]
        assert devices[0]["uid"] == "strip-7"
        assert devices[0]["reported"]["brightness"] == 55
        assert devices[0]["desired"]["brightness"] == 55  # adopted, not reset
        assert devices[0]["online"] is True

        # A command from the API arrives on the socket and the ack updates state.
        sent = auth_client.post("/api/devices/strip-7/props", json={"props": {"brightness": 20}})
        assert sent.status_code == 200
        command = json.loads(socket.receive_text())
        while command["t"] != "cmd":
            command = json.loads(socket.receive_text())
        assert command["props"] == {"brightness": 20}
        socket.send_text(json.dumps({"t": "ack", "id": command["id"], "ok": True,
                                     "state": {"power": True, "brightness": 20}}))
        time.sleep(0.3)
        refreshed = auth_client.get("/api/devices").json()["devices"][0]
        assert refreshed["reported"]["brightness"] == 20
